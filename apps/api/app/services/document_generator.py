def generate_proforma_invoice(data: dict[str, Any]) -> bytes:
    exporter = data.get("exporter", {})
    buyer = data.get("buyer", {})
    shipment = data.get("shipment", {})
    items = data.get("items", [])
    declarations = {**data.get("declarations", {}), "exporter_company_name": exporter.get("company_name", "")}

    buf = io.BytesIO()
    doc = _doc(buf, "PROFORMA INVOICE")
    s = _styles()
    story: list = []

    story.append(Paragraph("PROFORMA INVOICE", s["title"]))
    story.append(Paragraph("Subject to final commercial invoice on shipment.", s["subtitle"]))
    story.append(Spacer(1, 3 * mm))
    story += _header_table(exporter, buyer, shipment, s)
    story.append(Spacer(1, 3 * mm))
    story += _ref_table([
        ("Proforma Invoice No.", shipment.get("proforma_invoice_number") or shipment.get("invoice_number")),
        ("Proforma Invoice Date", shipment.get("proforma_invoice_date") or shipment.get("invoice_date")),
        ("Buyer Order / PO No.", shipment.get("buyer_order_number") or shipment.get("purchase_order_number")),
        ("Country of Origin", shipment.get("country_of_origin")),
        ("Country of Destination", shipment.get("country_of_final_destination")),
        ("Port of Loading", shipment.get("port_of_loading")),
        ("Port of Discharge", shipment.get("port_of_discharge")),
        ("Incoterm", f"{shipment.get('incoterm', '')} {shipment.get('port_of_discharge', '')} ({shipment.get('incoterms_version', 'Incoterms 2020')})"),
        ("Currency", shipment.get("currency")),
        ("Payment Terms", shipment.get("payment_terms")),
        ("Validity", shipment.get("validity") or "30 days from date"),
    ], s)
    story.append(Spacer(1, 4 * mm))

    item_tbl, totals = _item_table(items, include_packing=False, s=s)
    story += item_tbl
    story.append(Spacer(1, 2 * mm))
    cur = shipment.get("currency", "")
    story.append(Paragraph(f"<b>Total Invoice Value: {cur} {totals['total_value']:,.2f}</b>", s["value"]))

    if exporter.get("bank_name"):
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("Banking Details", s["h2"]))
        story += _ref_table([
            ("Bank Name", exporter.get("bank_name")),
            ("Account No.", exporter.get("bank_account")),
            ("IFSC/SWIFT", exporter.get("ifsc_swift")),
            ("AD Code", exporter.get("ad_code")),
        ], s)

    story += _signature_block(declarations, s)
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(DISCLAIMER, s["disclaimer"]))

    doc.build(story)
    return buf.getvalue()


def generate_commercial_invoice(data: dict[str, Any]) -> bytes:
    exporter = data.get("exporter", {})
    buyer = data.get("buyer", {})
    shipment = data.get("shipment", {})
    items = data.get("items", [])
    declarations = {**data.get("declarations", {}), "exporter_company_name": exporter.get("company_name", "")}

    buf = io.BytesIO()
    doc = _doc(buf, "COMMERCIAL INVOICE")
    s = _styles()
    story: list = []

    story.append(Paragraph("COMMERCIAL INVOICE", s["title"]))
    story.append(Spacer(1, 3 * mm))
    story += _header_table(exporter, buyer, shipment, s)
    story.append(Spacer(1, 3 * mm))
    story += _ref_table([
        ("Invoice No.", shipment.get("invoice_number")),
        ("Invoice Date", shipment.get("invoice_date")),
        ("Buyer Order / PO No.", shipment.get("buyer_order_number") or shipment.get("purchase_order_number")),
        ("Shipment Reference", shipment.get("shipment_reference")),
        ("Country of Origin", shipment.get("country_of_origin")),
        ("Country of Final Destination", shipment.get("country_of_final_destination")),
        ("Port of Loading", shipment.get("port_of_loading")),
        ("Port of Discharge", shipment.get("port_of_discharge")),
        ("Incoterm", f"{shipment.get('incoterm', '')} {shipment.get('port_of_discharge', '')} ({shipment.get('incoterms_version', 'Incoterms 2020')})"),
        ("Mode of Transport", shipment.get("mode_of_transport", "Sea").title()),
        ("Currency", shipment.get("currency")),
        ("Payment Terms", shipment.get("payment_terms")),
        ("Marks & Numbers", shipment.get("marks_and_numbers")),
    ], s)
    story.append(Spacer(1, 4 * mm))

    item_tbl, totals = _item_table(items, include_packing=False, s=s)
    story += item_tbl
    story.append(Spacer(1, 2 * mm))

    cur = shipment.get("currency", "")
    packing = data.get("packing", {})
    freight = packing.get("freight") or 0
    insurance = packing.get("insurance") or 0
    grand = totals["total_value"] + freight + insurance
    if freight or insurance:
        story += _ref_table([
            ("FOB Value", f"{cur} {totals['total_value']:,.2f}"),
            ("Freight", f"{cur} {freight:,.2f}" if freight else "—"),
            ("Insurance", f"{cur} {insurance:,.2f}" if insurance else "—"),
            ("Total Invoice Value (CIF)", f"{cur} {grand:,.2f}"),
        ], s)
    else:
        story.append(Paragraph(f"<b>Total Invoice Value: {cur} {grand:,.2f}</b>", s["value"]))

    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph("Declaration", s["h2"]))
    decl_text = declarations.get("declaration_of_origin") or (
        f"We hereby certify that the goods described in this invoice are of Indian origin "
        f"and that this invoice is true and correct."
    )
    story.append(Paragraph(decl_text, s["normal"]))

    story += _signature_block(declarations, s)
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(DISCLAIMER, s["disclaimer"]))

    doc.build(story)
    return buf.getvalue()


