"""Generate export documents (PDF) using reportlab.

All documents are exporter-prepared drafts. Declarations, authority limits, and
official filing channels are clearly stated in each document.

Document types supported:
  proforma_invoice | commercial_invoice | packing_list |
  commercial_invoice_cum_packing_list | shipping_instruction |
  coo_application_data_sheet | export_document_checklist
"""

from __future__ import annotations

